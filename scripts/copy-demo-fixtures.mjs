import { copyFile, mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const fixtureDirectory = join(projectRoot, "fixtures");
const publicDirectory = join(projectRoot, "public");
const generatedDirectory = join(projectRoot, "lib", "generated");
const demos = ["demo-instagram.zip", "demo-whatsapp.zip"];

await mkdir(publicDirectory, { recursive: true });
await mkdir(generatedDirectory, { recursive: true });

await Promise.all(
  demos.map((demo) =>
    copyFile(join(fixtureDirectory, demo), join(publicDirectory, demo)),
  ),
);

// Embed the Instagram demo so "Try synthetic export" never depends on a
// fragile public-folder fetch (OneDrive locks, stale SW, missing copy, etc.).
const instagramBytes = await readFile(
  join(fixtureDirectory, "demo-instagram.zip"),
);
const generatedSource = `/* Auto-generated by scripts/copy-demo-fixtures.mjs — do not edit. */
export const DEMO_INSTAGRAM_FILE_NAME = "demo-instagram.zip";
export const DEMO_INSTAGRAM_ZIP_BASE64 = "${instagramBytes.toString("base64")}";
`;

await writeFile(
  join(generatedDirectory, "demo-instagram.ts"),
  generatedSource,
  "utf8",
);

await writeFile(
  join(generatedDirectory, ".gitignore"),
  "demo-instagram.ts\n",
  "utf8",
);

console.log(
  `Copied ${demos.length} synthetic exports to public/ and embedded demo-instagram.zip (${instagramBytes.byteLength} bytes).`,
);
